// Write the differences between break and continue

/* Ans : In the C programming language, both break and continue are control flow statements used within loops.
The break statement is used to immediately terminate the loop or switch statement in which it appears. 
Once a break is encountered, the control exits the loop or switch block entirely, 
and the program continues with the next statement following that block.

The continue statement is used to skip the rest of the current iteration of a loop and 
jump to the next iteration.It does not terminate the loop entirely—only 
the current cycle of the loop is skipped when the condition is met.







*/